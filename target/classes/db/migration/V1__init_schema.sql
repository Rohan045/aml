-- external_txn_id is unique so replaying a feed is idempotent and cannot create
-- duplicate alerts. base_amount is the USD-normalised value every rule compares on.
create table transactions (
    id                     bigint generated by default as identity,
    external_txn_id        varchar(64) not null,
    account_id             varchar(32) not null,
    customer_id            varchar(32) not null,
    direction              varchar(10) not null,
    transaction_type       varchar(32) not null,
    channel                varchar(32),
    amount                 numeric(19,2) not null,
    currency               varchar(3)    not null,
    exchange_rate          numeric(19,8),
    base_amount            numeric(19,2) not null,
    base_currency          varchar(3)    not null,
    transaction_timestamp  timestamp(6) with time zone not null,
    value_date             date,
    status                 varchar(20) not null,
    narration              varchar(500),
    balance_after          numeric(19,2),
    counterparty_name      varchar(200),
    counterparty_account   varchar(64),
    counterparty_bank      varchar(200),
    counterparty_bank_code varchar(32),
    counterparty_country   varchar(2),
    origin_country         varchar(2),
    destination_country    varchar(2),
    is_cross_border        boolean     not null,
    merchant_category_code varchar(8),
    branch_code            varchar(20),
    device_id              varchar(100),
    ip_address             varchar(64),
    screening_status       varchar(20) not null,
    screened_at            timestamp(6) with time zone,
    ingestion_batch_id     bigint,
    created_at             timestamp(6) with time zone not null,
    created_by             varchar(100),
    updated_at             timestamp(6) with time zone,
    updated_by             varchar(100),
    primary key (id),
    constraint uk_transaction_external_id unique (external_txn_id),
    constraint fk_transaction_account foreign key (account_id) references accounts (account_id),
    constraint fk_transaction_customer foreign key (customer_id) references customers (customer_id),
    constraint ck_txn_direction check (direction in ('CREDIT','DEBIT')),
    constraint ck_txn_type check (transaction_type in
        ('CASH_DEPOSIT','CASH_WITHDRAWAL','TRANSFER_IN','TRANSFER_OUT','WIRE_IN','WIRE_OUT',
         'CHEQUE_DEPOSIT','CHEQUE_WITHDRAWAL','CARD_PAYMENT','BILL_PAYMENT','LOAN_DISBURSEMENT',
         'LOAN_REPAYMENT','INTEREST_CREDIT','FEE_DEBIT','REVERSAL','OTHER')),
    constraint ck_txn_channel check (channel in
        ('BRANCH','ATM','INTERNET_BANKING','MOBILE_APP','PHONE_BANKING','UPI','IMPS','NEFT',
         'RTGS','SWIFT','CARD_POS','CASH_COUNTER','CHEQUE','STANDING_INSTRUCTION','OTHER')),
    constraint ck_txn_status check (status in
        ('PENDING','POSTED','SETTLED','FAILED','REVERSED','HELD')),
    constraint ck_txn_screening_status check (screening_status in
        ('PENDING','IN_PROGRESS','SCREENED','FAILED','SKIPPED')),
    constraint ck_txn_amount_positive check (amount > 0),
    constraint ck_txn_base_amount_positive check (base_amount > 0)
);

-- Windowed rule lookups (structuring, rapid movement, behavioural deviation) always
-- filter by account or customer plus a time range, hence the composite indexes.
create index idx_txn_account_time on transactions (account_id, transaction_timestamp);
create index idx_txn_customer_time on transactions (customer_id, transaction_timestamp);
create index idx_txn_timestamp on transactions (transaction_timestamp);
create index idx_txn_screening_status on transactions (screening_status);
create index idx_txn_base_amount on transactions (base_amount);
create index idx_txn_counterparty_country on transactions (counterparty_country);
create index idx_txn_batch on transactions (ingestion_batch_id);

