    deviation_multiplier numeric(9,2),
    lookback_days        integer,
    ratio_threshold      numeric(5,4),
    dedupe_window_hours  integer,
    parameters           text,
    config_version       integer      not null,
    effective_from       timestamp(6) with time zone,
    effective_to         timestamp(6) with time zone,
    last_tuned_by        varchar(100),
    last_tuned_at        timestamp(6) with time zone,
    created_at           timestamp(6) with time zone not null,
    created_by           varchar(100),
    updated_at           timestamp(6) with time zone,
    updated_by           varchar(100),
    primary key (id),
    constraint uk_rule_code unique (rule_code),
    constraint ck_rule_typology check (typology in
