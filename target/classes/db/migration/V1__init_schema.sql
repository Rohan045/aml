    updated_at      timestamp(6) with time zone,
    updated_by      varchar(100),
    primary key (id),
    constraint uk_alert_evidence_txn unique (alert_id, transaction_id),
    constraint fk_evidence_alert foreign key (alert_id) references alerts (id),
    constraint fk_evidence_transaction foreign key (transaction_id) references transactions (id)
);

create index idx_evidence_alert on alert_evidence (alert_id);
create index idx_evidence_transaction on alert_evidence (transaction_id);

-- -----------------------------------------------------------------------------
-- Immutable audit trail
-- -----------------------------------------------------------------------------

-- Insert-only. Every alert / case / rule state transition lands here with the
-- acting identity and timestamp. Never expose an update or delete path.
create table audit_events (
    id             bigint generated by default as identity,
    entity_type    varchar(40)  not null,
    entity_id      varchar(64)  not null,
    action         varchar(40)  not null,
    from_state     varchar(40),
    to_state       varchar(40),
    actor          varchar(100) not null,
    actor_role     varchar(40),
    occurred_at    timestamp(6) with time zone not null,
    details        text,
    correlation_id varchar(64),
    ip_address     varchar(64),
    primary key (id),
    constraint ck_audit_action check (action in
        ('CREATED','UPDATED','STATUS_CHANGED','ASSIGNED','REASSIGNED','ESCALATED','DISPOSITIONED',
         'CLOSED','REOPENED','NOTE_ADDED','RULE_ENABLED','RULE_DISABLED','RULE_TUNED',
         'PII_REVEALED','INGESTION_STARTED','INGESTION_COMPLETED','SAR_DRAFTED','SAR_FILED','LOGIN'))
);

create index idx_audit_entity on audit_events (entity_type, entity_id);
create index idx_audit_actor on audit_events (actor);
create index idx_audit_occurred_at on audit_events (occurred_at);
create index idx_audit_action on audit_events (action);
