-- Quarantine for rejected records so a bad row never aborts the whole batch.
create table ingestion_errors (
    id                bigint generated by default as identity,
    batch_id          bigint        not null,
    record_number     integer,
    record_identifier varchar(64),
    field_name        varchar(100),
    error_code        varchar(64)   not null,
    error_message     varchar(1000) not null,
    raw_record        text,
    occurred_at       timestamp(6) with time zone not null,
    primary key (id),
    constraint fk_ingestion_error_batch foreign key (batch_id)
        references ingestion_batches (id)
);

create index idx_ingestion_error_batch on ingestion_errors (batch_id);
create index idx_ingestion_error_code on ingestion_errors (error_code);

