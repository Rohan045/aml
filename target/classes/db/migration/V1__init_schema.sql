-- =============================================================================
-- Sentinel AML - V1 baseline schema
--
-- Entity relationships:
--   customers 1---* accounts 1---* transactions
--   customers 1---* alerts *---1 aml_cases
--   alerts    1---* alert_triggered_rules      (why it fired)
--   alerts    1---* alert_evidence *---1 transactions  (what it fired on)
--
-- Conventions:
--   * snake_case identifiers, plural table names
--   * all money columns numeric(19,2); FX rates numeric(19,8)
--   * all instants stored as timestamptz(6) in UTC
--   * enums persisted as varchar with a CHECK constraint (portable, greppable)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Reference / configuration
-- -----------------------------------------------------------------------------

-- Configurable FX rates used to normalise every amount into the base currency (USD).
-- Effective-dated so historical alerts stay reproducible.
create table exchange_rates (
    id             bigint generated by default as identity,
    from_currency  varchar(3)      not null,
    to_currency    varchar(3)      not null,
    rate           numeric(19,8)   not null,
    effective_from date            not null,
    effective_to   date,
    source         varchar(120),
    created_at     timestamp(6) with time zone not null,
    created_by     varchar(100),
    updated_at     timestamp(6) with time zone,
    updated_by     varchar(100),
    primary key (id),
    constraint uk_rate_currency_effective unique (from_currency, to_currency, effective_from),
    constraint ck_exchange_rate_positive check (rate > 0)
);

create index idx_rate_lookup on exchange_rates (from_currency, to_currency, effective_from);

-- High-risk jurisdictions and counterparties. One table serves both the
-- high-risk-jurisdiction and high-risk-counterparty rules.
create table watchlist_entries (
    id               bigint generated by default as identity,
    subject_type     varchar(32)  not null,
    list_type        varchar(32)  not null,
    entry_value      varchar(200) not null,
    normalized_value varchar(200) not null,
    display_name     varchar(200),
    risk_weight      integer      not null,
    source           varchar(120),
    active           boolean      not null,
    effective_from   timestamp(6) with time zone,
    effective_to     timestamp(6) with time zone,
    notes            text,
    created_at       timestamp(6) with time zone not null,
    created_by       varchar(100),
    updated_at       timestamp(6) with time zone,
    updated_by       varchar(100),
    primary key (id),
    constraint uk_watchlist_subject_value unique (subject_type, list_type, normalized_value),
    constraint ck_watchlist_subject_type check (subject_type in
        ('COUNTRY','COUNTERPARTY','BANK','INDIVIDUAL','ENTITY','ACCOUNT_NUMBER')),
    constraint ck_watchlist_list_type check (list_type in
        ('SANCTIONS','FATF_BLACKLIST','FATF_GREYLIST','TAX_HAVEN','PEP','ADVERSE_MEDIA','INTERNAL_HIGH_RISK')),
    constraint ck_watchlist_risk_weight check (risk_weight >= 0)
);

create index idx_watchlist_lookup on watchlist_entries (subject_type, normalized_value, active);
create index idx_watchlist_list_type on watchlist_entries (list_type);

