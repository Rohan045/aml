-- dedupe_key is UNIQUE: it is the database-level guarantee that concurrent
-- detection threads cannot raise redundant alerts for one underlying pattern.
-- A repeat detection increments occurrence_count instead of inserting a new row.
create table alerts (
    id                     bigint generated by default as identity,
    alert_reference        varchar(32)  not null,
    customer_id            varchar(32)  not null,
    account_id             varchar(32),
    typology               varchar(40)  not null,
    status                 varchar(20)  not null,
    severity               varchar(20)  not null,
    risk_score             integer      not null,
    title                  varchar(200) not null,
    explanation            text         not null,
    dedupe_key             varchar(255) not null,
    occurrence_count       integer      not null,
    detection_window_start timestamp(6) with time zone,
    detection_window_end   timestamp(6) with time zone,
    first_detected_at      timestamp(6) with time zone not null,
    last_detected_at       timestamp(6) with time zone not null,
    total_amount           numeric(19,2),
    transaction_count      integer,
    assigned_to            varchar(100),
    assigned_at            timestamp(6) with time zone,
    case_id                bigint,
    disposition            varchar(32),
    disposition_reason     text,
    disposition_by         varchar(100),
    disposition_at         timestamp(6) with time zone,
    version                bigint not null,
    created_at             timestamp(6) with time zone not null,
    created_by             varchar(100),
    updated_at             timestamp(6) with time zone,
    updated_by             varchar(100),
    primary key (id),
    constraint uk_alert_reference unique (alert_reference),
    constraint uk_alert_dedupe_key unique (dedupe_key),
    constraint fk_alert_customer foreign key (customer_id) references customers (customer_id),
    constraint fk_alert_account foreign key (account_id) references accounts (account_id),
    constraint fk_alert_case foreign key (case_id) references aml_cases (id),
    constraint ck_alert_typology check (typology in
        ('THRESHOLD_BREACH','STRUCTURING','RAPID_MOVEMENT','HIGH_RISK_JURISDICTION',
         'BEHAVIOURAL_DEVIATION','ROUND_AMOUNT_PATTERN','HIGH_RISK_COUNTERPARTY',
         'DORMANT_ACCOUNT_REACTIVATION','ANOMALY_SCORE')),
    constraint ck_alert_status check (status in
        ('NEW','ASSIGNED','IN_REVIEW','PENDING_INFO','ESCALATED','CLOSED')),
    constraint ck_alert_severity check (severity in ('LOW','MEDIUM','HIGH','CRITICAL')),
    constraint ck_alert_disposition check (disposition in
        ('TRUE_POSITIVE','FALSE_POSITIVE','ESCALATED_TO_CASE','SAR_FILED','DUPLICATE',
         'INSUFFICIENT_EVIDENCE','RISK_ACCEPTED')),
    constraint ck_alert_risk_score check (risk_score between 0 and 100),
    constraint ck_alert_occurrence_count check (occurrence_count >= 1),
    -- An alert may only be closed once a disposition and the deciding analyst are recorded.
    constraint ck_alert_closed_requires_disposition check (
        status <> 'CLOSED' or (disposition is not null and disposition_by is not null))
);

-- Analyst queue: open alerts sorted by descending risk score.
create index idx_alert_status_score on alerts (status, risk_score);
create index idx_alert_customer on alerts (customer_id);
create index idx_alert_account on alerts (account_id);
create index idx_alert_typology on alerts (typology);
create index idx_alert_severity on alerts (severity);
create index idx_alert_case on alerts (case_id);
create index idx_alert_detected_at on alerts (first_detected_at);

